param([string]$OutDir='')
$ErrorActionPreference='Stop'
$root=(Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path
$boardSource=Get-Content (Join-Path $root 'rtl/platform/tang_mega_138k_pro/instrument_system.sv') -Raw
$baseMatch=[regex]::Match($boardSource,"\.FLASH_BASE\(32'h([0-9a-fA-F_]+)\)")
if(!$baseMatch.Success){throw 'Cannot determine board Flash resource base'}
$flashBase=[Convert]::ToInt64($baseMatch.Groups[1].Value.Replace('_',''),16)
if(!$OutDir){$OutDir=Join-Path $root 'build/phase1_delivery'}
$null=New-Item -ItemType Directory -Force $OutDir
$OutDir=(Resolve-Path $OutDir).Path
$pianoPath=Join-Path $PSScriptRoot 'piano_flash.bin'
$guitarPath=Join-Path $PSScriptRoot 'guitar_flash.bin'
$piano=[IO.File]::ReadAllBytes($pianoPath)
$guitar=[IO.File]::ReadAllBytes($guitarPath)
$tableBytes=16*64*64
if($piano.Length -ne $tableBytes -or $guitar.Length -ne 2*$tableBytes){throw 'Expected legacy 16-note, 64-mode resources'}
for($i=0;$i -lt $tableBytes;$i++){if($guitar[$i] -ne 255){throw 'Guitar image prefix is not erased padding'}}
$merged=New-Object byte[] (2*$tableBytes)
[Array]::Copy($piano,0,$merged,0,$tableBytes)
[Array]::Copy($guitar,$tableBytes,$merged,$tableBytes,$tableBytes)
# Check records before publishing an image. Guitar unused modes are zero padding.
for($inst=0;$inst -lt 2;$inst++){
    for($slot=0;$slot -lt 16;$slot++){
        $activeModes=if($inst -eq 0){64}else{20}
        for($mode=0;$mode -lt $activeModes;$mode++){
            $offset=$inst*$tableBytes+($slot*64+$mode)*64
            $record=$merged[$offset..($offset+63)]
            if(($record | Where-Object {$_ -ne 255}).Count -eq 0 -or ($record | Where-Object {$_ -ne 0}).Count -eq 0){throw "Blank record inst=$inst slot=$slot mode=$mode"}
            if(($merged[($offset+28)..($offset+31)] | Where-Object {$_ -ne 0}).Count){throw 'Reserved word must be zero'}
        }
    }
}
$bin=Join-Path $OutDir 'piano_guitar_16.bin'
[IO.File]::WriteAllBytes($bin,$merged)
$mem=Join-Path $OutDir 'piano_guitar_16.mem'
$lines=foreach($value in $merged){'{0:X2}' -f $value}
[IO.File]::WriteAllLines($mem,[string[]]$lines,[Text.Encoding]::ASCII)
$model=Join-Path $OutDir 'MEM.TXT'
[IO.File]::WriteAllLines($model,[string[]](@('@000000')+$lines),[Text.Encoding]::ASCII)
$notes=@(40,42,44,46,48,50,52,54,56,58,60,62,64,67,71,76)
$manifest=[ordered]@{
    schema=1;format='ENG0_MATRIX_FIXED_Q';note_banks=$false;resource_mask=3
    storage_modes=64;record_bytes=64;notes=$notes;table_bytes=$tableBytes
    flash_start_address=$flashBase;image_bytes=$merged.Length
    configuration_start_address=0;simulation_flash_start_address=0
    resource_sample_hz=48000;board_sample_hz=48828.125;pcm_headroom_bits=4
    image_sha256=(Get-FileHash $bin -Algorithm SHA256).Hash.ToLowerInvariant()
    instruments=@(
        @{id=0;name='piano';offset=0;flash_address=$flashBase;bytes=$tableBytes;active_modes=64;source_sha256=(Get-FileHash $pianoPath -Algorithm SHA256).Hash.ToLowerInvariant()},
        @{id=1;name='guitar';offset=$tableBytes;flash_address=($flashBase+$tableBytes);bytes=$tableBytes;active_modes=20;source_sha256=(Get-FileHash $guitarPath -Algorithm SHA256).Hash.ToLowerInvariant()}
    )
}
$manifest | ConvertTo-Json -Depth 8 | Set-Content -Encoding utf8 (Join-Path $OutDir 'resources.json')
$pkg=@'
// Generated by rtl/router/tools/pack_phase1.ps1; matching resources.json required.
package phase1_resources_pkg;
    localparam logic [9:0] RESOURCE_MASK=10'b0000000011;
    localparam int NOTES=16, STORAGE_MODES=64, RECORD_BYTES=64;
    localparam int PCM_HEADROOM_BITS=4;
endpackage
'@
[IO.File]::WriteAllText((Join-Path $root 'rtl/platform/tang_mega_138k_pro/phase1_resources_pkg.sv'),$pkg,[Text.Encoding]::ASCII)
Write-Output ("PASS phase1 pack: {0} ({1} bytes); program BIN at 0x{2:X6}; guitar image offset 0x010000" -f $bin,$merged.Length,$flashBase)

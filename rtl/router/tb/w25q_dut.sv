// =============================================================================
// w25q_dut -- 把公开的 W25Q128JVxIM 行为模型包成"4 位 DQ 总线"的引脚适配层
//
// **只有端口映射，没有任何协议逻辑**（这一点很重要：基准实现不能被我们改写）。
// 模型的四个引脚在三线/四线模式下就是：
//     DIO = DQ0    DO = DQ1    WPn = DQ2    HOLDn = DQ3
// 它们都是 inout 且模型内部自带 tri-state，所以直接并到同一根 4 位网上即可：
// 谁在驱动由各自的 OE 决定（主机侧由 TB 用 1'bz 让出）。
// =============================================================================
`timescale 1ns/1ps

module w25q_dut (
    input  wire        cs_n,      // 片选（低有效）
    input  wire        sck,       // 时钟
    inout  wire [3:0]  dq         // 四线数据（DQ0..DQ3）
);

    W25Q128JVxIM u_flash (
        .CSn  (cs_n),
        .CLK  (sck),
        .DIO  (dq[0]),
        .DO   (dq[1]),
        .WPn  (dq[2]),
        .HOLDn(dq[3])
    );

endmodule

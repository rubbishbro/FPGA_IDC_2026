#!/usr/bin/env python3
"""Offline dyadic lip calibration; no synthesis, audio render or RTL simulation.

The positive triangle lasts four times as long as the negative triangle.
Its negative slope is 16x the positive slope, giving exactly zero discrete area.
Three signed powers of two approximate the unit-fundamental input gain.
"""
from pathlib import Path
import json
import math
import numpy as np

ROOT = Path(__file__).resolve().parents[3]


def configurations():
    rows = []
    for midi in range(51, 83):
        period = round(48000/(440*2**((midi-69)/12)))
        half_shift = max(2, round(math.log2(.06*period)))
        half = 1 << half_shift
        close = half >> 2
        gap = max(1, round(.02*period))
        opening = np.r_[np.arange(1, half+1), np.arange(half-1, -1, -1)]
        closing = -16*np.r_[np.arange(1, close+1), np.arange(close-1, -1, -1)]
        shape = np.r_[opening, np.zeros(gap), closing]
        target = 1/abs(np.sum(shape*np.exp(-2j*np.pi*np.arange(len(shape))/period)))
        remainder = target
        shifts, negative = [], []
        for _ in range(3):
            sign = -1 if remainder < 0 else 1
            shift = min(30, max(1, round(-math.log2(max(abs(remainder), 1e-30)))))
            shifts.append(shift)
            negative.append(sign < 0)
            remainder -= sign*2**(-shift)
        actual = sum((-1 if n else 1)*2**(-s) for s, n in zip(shifts, negative))
        # Noise LP alpha=1/2 plus DC-removal alpha=1/16; approximate RMS gain.
        air_shift = round(math.log2(math.sqrt(period)*1.7/.005))
        assert shape.sum() == 0 and len(shape) < period and actual > 0
        rows.append(dict(midi=midi, period=period, half_shift=half_shift, gap=gap,
                         shifts=shifts, negative=negative, air_shift=air_shift,
                         fundamental_gain_error_db=20*math.log10(actual/target)))
    return rows


def main():
    rows = configurations()
    lines = ['// Generated by rtl/router/tools/trumpet_excitation_rom.py.',
             '// Fixed 48kHz / MIDI51..82; gains use at most three shifted terms.',
             'package trumpet_excitation_pkg;',
             '    typedef struct packed {',
             '        logic valid;',
             '        logic [2:0] half_shift;',
             '        logic [4:0] gap;',
             '        logic [4:0] shift0,shift1,shift2;',
             '        logic [2:0] negative;',
             '        logic [3:0] air_shift;',
             '    } lip_cfg_t;',
             '    function automatic lip_cfg_t lip_config(input logic[15:0] period);',
             '        case(period)']
    for r in rows:
        signs = sum(int(n) << i for i, n in enumerate(r['negative']))
        s = r['shifts']
        lines.append(f"            16'd{r['period']}:return {{1'b1,3'd{r['half_shift']},5'd{r['gap']},"
                     f"5'd{s[0]},5'd{s[1]},5'd{s[2]},3'd{signs},4'd{r['air_shift']}}}; // MIDI{r['midi']}")
    lines += ["            default:return '0;", '        endcase', '    endfunction', 'endpackage', '']
    (ROOT/'rtl/router/pkg/trumpet_excitation_pkg.sv').write_text('\n'.join(lines))
    (Path(__file__).parent/'performance/trumpet_excitation.json').write_text(
        json.dumps(dict(sample_rate=48000,method='zero-area bipolar triangles; three signed power-of-two gain terms',
                        opening_to_closing_duration=4,entries=rows),indent=2)+'\n')
    print('Generated',len(rows),'periods; worst fundamental gain error',
          max(abs(r['fundamental_gain_error_db']) for r in rows),'dB')


if __name__ == '__main__':
    main()

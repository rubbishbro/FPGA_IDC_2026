#!/usr/bin/env python3
"""Generate small control ROMs; all runtime products share eng1_pitch's one DSP."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'python/modal_sim'))
import pitch_linear as P
lines=['// Generated by rtl/router/tools/pitch_tables.py; cents Q8, ratio Q24.',
       'package pitch_tables_pkg;',f'    localparam int PITCH_TAG=32\'h{P.TAG:08x};',
       f'    localparam int LFO_STEP={P.LFO_STEP};']
for name,width,signed,values in [('pitch_ratio',25,False,P.ratio_table()),('pitch_sine',16,True,P.sine_table()),('pitch_depth',14,False,P.depth_table())]:
 lines += [f'    function automatic logic {"signed " if signed else ""}[{width-1}:0] {name}(input logic [8:0] address);','        case(address)']
 for i,v in enumerate(values):
  lines.append(f"            9'd{i}: {name}={width}'h{v&((1<<width)-1):x};")
 lines += [f"            default: {name}='0;",'        endcase','    endfunction']
lines += ['endpackage','']
(ROOT/'rtl/router/pkg/pitch_tables_pkg.sv').write_text('\n'.join(lines))

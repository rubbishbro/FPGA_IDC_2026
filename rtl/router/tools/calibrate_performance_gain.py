#!/usr/bin/env python3
"""Calibrate six instrument gains with one PCM headroom and unity-center pan."""
from pathlib import Path
import argparse,hashlib,json,math,sys
import numpy as np
from scipy.signal import sosfilt

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'python/modal_sim'))
from performance_chain import RawPerformance
import router_eng1 as R

GAIN_DEPENDENCIES=(
    'rtl/router/tools/calibrate_performance_gain.py',
    'rtl/router/tools/performance_resources.py',
    'python/modal_sim/performance_chain.py','python/modal_sim/eng1_rtl.py',
    'python/modal_sim/router_eng1.py','python/modal_sim/eng1_audition.py',
    'rtl/router/pkg/modal_step_pkg.sv','rtl/router/pkg/router_pkg.sv',
    'rtl/router/routers/body_router.sv','rtl/router/routers/env_router.sv',
    'rtl/router/routers/exc_router.sv','rtl/router/parts/polyphony_gain.sv',
    'rtl/router/voice_router.sv',
    'rtl/platform/tang_mega_138k_pro/instrument_board_top.sv',
    'rtl/platform/tang_mega_138k_pro/instrument_system.sv')

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--directory',type=Path,default=Path(__file__).parent/'performance')
    args=ap.parse_args();d=args.directory
    m=json.loads((d/'resources.json').read_text());image=(d/'resources.bin').read_bytes()
    results={};headroom=3;fs=48000;n=32000;hold=28000
    traces=ROOT/'build/performance_gain_calibration';traces.mkdir(parents=True,exist_ok=True)
    for name in m['frontends']:
        model=RawPerformance(name,m,image);raw=np.empty((n,model.slots),dtype=np.int64);counts=np.empty(n,dtype=np.int64)
        for i in range(n):
            raw[i],env,dead=model.step(np.full(model.slots,i<hold),np.full(model.slots,255))
            counts[i]=np.count_nonzero((env>0)&~dead)
        rows=R.body_coeffs(name)
        sos=np.array([[*np.array(c[:3])/(1<<27),1.,*np.array(c[3:])/(1<<27)] for c in rows])
        filtered=sosfilt(sos,raw.astype(float),axis=0)
        # Same headroom/PCM reference for every engine; no per-file RMS gain.
        norm=filtered/float(1<<(24+headroom))
        energy=np.vstack([np.zeros((1,model.slots)),np.cumsum(norm[:9600]**2,axis=0)])
        rms=np.sqrt(np.max((energy[960:]-energy[:-960])/960,axis=0))
        median=float(np.median(rms));target=10**(-18/20)
        peaks=np.max(abs(norm),axis=0)
        gains=np.minimum(128.,np.minimum(target/np.maximum(rms,1e-12),10**(-3/20)/np.maximum(peaks,1e-12)))
        count_gain=4096;smoothed=np.empty(n)
        for i,count in enumerate(counts):
            wanted=count_gain if count==0 else round(4096/math.sqrt(count))
            if wanted<count_gain:count_gain-=max(1,(count_gain-wanted)>>3)
            elif wanted>count_gain:count_gain+=max(1,(wanted-count_gain)>>12)
            smoothed[i]=count_gain/4096
        chord=np.sum(norm*gains[None,:],axis=1)*smoothed
        common=min(1.,10**(-1/20)/max(float(abs(chord).max()),1e-12))
        gains*=common
        qs=np.maximum(1,np.floor(gains*4096)).astype(np.int64)
        ident=next(r['instrument'] for r in m['entries'] if r['name']==name)
        results[name]=dict(instrument=ident,note_gain_q12=dict(zip(map(str,m['note_map']),map(int,qs))),
            raw_median_max20ms_rms_dbfs=20*math.log10(max(median,1e-30)),
            calibrated_median_max20ms_rms_dbfs=20*math.log10(max(float(np.median(rms*qs/4096)),1e-30)),
            calibrated_single_note_peak_dbfs=20*math.log10(max(float(np.max(peaks*qs/4096)),1e-30)),
            simultaneous_16_note_trim=common,
            simultaneous_16_note_peak_dbfs=20*math.log10(max(float(abs(np.sum(norm*(qs/4096)[None,:],axis=1)*smoothed).max()),1e-30)),
            per_note_raw_rms_dbfs=(20*np.log10(np.maximum(rms,1e-30))).tolist())
        np.save(traces/f'{name}_raw_q24.npy',filtered)
        print(name,'gain range',float(qs.min()/4096),float(qs.max()/4096),results[name]['calibrated_median_max20ms_rms_dbfs'],flush=True)
    norm=[4096]+[round(4096/math.sqrt(i)) for i in range(1,17)]
    meta=dict(schema=1,headroom=headroom,pan='max(L,R)=1; center unity',
        fixture='16 independent notes, velocity255 held28000/32000 frames, no pressure modulation; maximum 960-frame RMS in first9600 frames',
        target_max20ms_rms_dbfs=-18,single_note_peak_ceiling_dbfs=-3,simultaneous_16_note_peak_ceiling_dbfs=-1,
        calibration_body='quantized Q27 coefficients, float SOS for gain measurement only',
        dynamic_policy='1/sqrt(N), count envelope-active voices including release; fast attenuation, slow recovery; hold gain at N=0',
        normalization_q12=norm,instruments=results,
        resources_sha256=hashlib.sha256(image).hexdigest(),
        source_hashes={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in GAIN_DEPENDENCIES})
    (d/'gain.json').write_text(json.dumps(meta,indent=2,ensure_ascii=False)+'\n')
    lines=['// Generated by calibrate_performance_gain.py; shared headroom=3.',
        'package performance_gain_pkg;',
        '    function automatic logic[19:0] note_gain(input router_pkg::instrument_e inst,input logic[6:0] note);',
        '        case({inst,note})']
    for row in results.values():
        for note,value in row['note_gain_q12'].items():lines.append(f"            11'd{row['instrument']*128+int(note)}:return 20'd{value};")
    lines += ["            default:return 20'd4096;",'        endcase','    endfunction',
        '    function automatic logic[12:0] count_scale(input logic[4:0] count);','        case(count)']
    for i,value in enumerate(norm):lines.append(f"            5'd{i}:return 13'd{value};")
    lines += ["            default:return 13'd1024;",'        endcase','    endfunction','endpackage','']
    (ROOT/'rtl/router/pkg/performance_gain_pkg.sv').write_text('\n'.join(lines))


if __name__=='__main__':main()

// -----------------------------------------------------------------------------
// clock_reset.sv -- Tang Mega 138K Pro clock / reset wrapper.
//
// The board 50 MHz crystal (clk, P16) feeds TWO Gowin PLL IP modules generated
// with the Gowin IP Core Generator (PLL_ADV, target GW5AST-138B / FPG676AES):
//
//   * Gowin_PLL_core_100M -> clkout0 = 100.000 MHz (core clock)
//   * Gowin_PLL_audio_12M5 -> clkout0 = 12.500 MHz (audio reference)
//
// AUDIO RATE CAVEAT: exact 12.288 MHz is NOT generatable from the 50 MHz crystal
// on this part (PFD must be 19-81.25 MHz; no exact solution exists).  The 12.5 MHz
// PLL produced by the real tool gives BCLK 3.125 MHz and LRC 48.828125 kHz
// (+1.725% rate / +29.6 cents pitch vs 48 kHz).  It is a functional bring-up
// clock, NOT a 48 kHz-faithful reference; the ROM coefficients are still the 48
// kHz set, so the diagnostic comparison is expected to differ by that ratio.
//
// REAL vendor interface, produced by Gowin V1.9.12.04:
//     Gowin_PLL_core_100M  (clkin, init_clk, clkout0, lock);
//     Gowin_PLL_audio_12M5 (clkin, init_clk, clkout0, lock);
// `init_clk` is a free-running reference for the IP's internal PLL_INIT lock
// FSM (here the 50 MHz crystal).  There is NO user `reset`/`enclk*` port: the IP
// brings itself up; the board reset and the "shut down until locked" policy are
// implemented at the rst_n / output stage below.
//
// The generated files live under rtl/platform/tang_mega_138k_pro/ip/ and are
// listed in sources.f.  They must NOT be replaced by a behavioural model here:
// if the IP is missing the build fails.  The test-only stand-in used by the
// board simulation is sim/audio_helpers/board_pll_model.sv (same port list).
//
// Reset policy:
//   * the active-high board button forces rst_n low immediately;
//   * rst_n is released only after BOTH PLLs report lock;
//   * rst_n is asserted combinationally the moment lock is lost, so downstream
//     logic and the amplifier shutdown pin stop immediately.
// -----------------------------------------------------------------------------
`timescale 1ns/1ps

module clock_reset (
    input  logic clk_50m,      // 50 MHz crystal, board pin P16
    input  logic rst_btn,      // board reset button, pin U4, ACTIVE HIGH
    output logic clk_core,     // 100 MHz  (PLL core)
    output logic clk_audio,    // 12.5 MHz (PLL audio; NOT exact 12.288 -- see header)
    output logic locked,       // both PLLs locked
    output logic rst_n         // active-low, released after lock, drops on unlock
);

    // ------------------------------------------------------------------
    // vendor PLL IP instantiations (generated by Gowin; not simulated here)
    // ------------------------------------------------------------------
    logic core_lock, audio_lock;

    Gowin_PLL_core_100M u_pll_core (
        .clkin   (clk_50m),
        .init_clk(clk_50m),
        .clkout0 (clk_core),
        .lock    (core_lock)
    );

    Gowin_PLL_audio_12M5 u_pll_audio (
        .clkin   (clk_50m),
        .init_clk(clk_50m),
        .clkout0 (clk_audio),
        .lock    (audio_lock)
    );

    assign locked = core_lock & audio_lock;

    // ------------------------------------------------------------------
    // core-domain reset release.  Async assert on button or !locked so rst_n
    // falls in the same cycle lock drops; release is 3 core clocks after lock.
    // ------------------------------------------------------------------
    logic [2:0] crst_sync;
    always_ff @(posedge clk_core or negedge locked)
        if (!locked) crst_sync <= 3'b000;
        else         crst_sync <= {crst_sync[1:0], 1'b1};

    assign rst_n = crst_sync[2] & locked & ~rst_btn;

endmodule

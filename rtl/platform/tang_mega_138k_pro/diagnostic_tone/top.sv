// -----------------------------------------------------------------------------
// top.sv -- standalone CONTINUOUS DIAGNOSTIC TONE board top (Tang Mega 138K Pro).
//
// This is a deliberately minimal, self-contained bring-up design.  It is NOT the
// automatic-song project and does not instantiate or replace any of the song,
// FIFO, modal-engine, body-filter or microphone logic.  It exists so a board can
// be checked for a stable, known I2S tone with the smallest possible RTL.
//
// Real board interface only:
//   clk      : 50 MHz crystal, pin P16
//   amp_*    : PMOD2 / J26 -> external MAX98357A (same 3.3 V wiring as the main
//              project): amp_bclk = C21 (BCLK), amp_lrc = B20 (LRC/WS),
//              amp_din  = B19 (DIN), amp_sd = A17 (shutdown / channel select).
//
// There is deliberately NO board reset / button port (the main design uses U4):
// the only state control is the audio PLL lock.  The design therefore does NOT
// depend on any button, and cannot be left muted by an unconfirmed key.
//
// Clocking: ONLY the existing real Gowin PLL IP Gowin_PLL_audio_12M5 is used; the
// 100 MHz core PLL is NOT needed and NOT instantiated.  clk -> 12.5 MHz audio.
// 12.5 MHz is the real vendor PLL output, NOT exact 12.288 MHz (see
// clock_reset.sv / BOARD_README): BCLK = 3.125 MHz, LRC = 48.828125 kHz.  The
// tone frequency is 48828.125/48 = 1017.252604166... Hz, amplitude -30.10 dBFS.
//
// Reset: a 3FF synchroniser in the audio domain asserts asynchronously the moment
// the PLL reports no lock and releases synchronously 3 audio clocks after lock
// returns.  BOTH the tone source and the I2S transmitter use
//   rst_n = rst_sync[2]
// i.e. the reset RELEASE is driven ONLY by the synchronised last stage; the raw
// 50 MHz lock is NOT ANDed into the normal-state CLEAR tree.  (ANDing raw lock in
// would let the asynchronous lock bypass the synchroniser and violate removal at
// every normal state register.)  A lost lock still clears the datapath
// asynchronously: raw audio_locked asynchronously clears rst_sync, whose last
// stage then asynchronously clears the normal state.  Re-lock always restarts
// from the first frame.
//
// amp_sd is gated combinationally on lock, reset and the sticky tone `started`
// flag.  It goes low in the same cycle lock is lost, and is re-enabled only after
// the first full frame accepted following re-lock.  No button, ROM or core
// signal can hold it high.
// -----------------------------------------------------------------------------
`timescale 1ns/1ps

module diagnostic_tone_top (
    input  logic clk,        // 50 MHz crystal, board pin P16
    output logic amp_bclk,   // PMOD2 IO0 / C21 -> MAX98357A BCLK
    output logic amp_lrc,    // PMOD2 IO1 / B20 -> MAX98357A LRC/WS
    output logic amp_din,    // PMOD2 IO2 / B19 -> MAX98357A DIN
    output logic amp_sd      // PMOD2 IO3 / A17 -> MAX98357A SD (high = left)
);

    // ------------------------------------------------------------------
    // Real vendor PLL IP (user-generated, present under ../ip/).
    // Port list exactly as generated by Gowin V1.9.12.04:
    //   Gowin_PLL_audio_12M5 (clkin, init_clk, clkout0, lock)
    // There is no user reset/enclk port; the IP brings itself up.
    // ------------------------------------------------------------------
    logic clk_audio;        // 12.5 MHz audio reference
    logic audio_locked;     // PLL lock

    Gowin_PLL_audio_12M5 u_pll_audio (
        .clkin   (clk),
        .init_clk(clk),
        .clkout0 (clk_audio),
        .lock    (audio_locked)
    );

    // ------------------------------------------------------------------
    // Audio-domain reset: 3FF, asynchronous assert on loss of lock, synchronous
    // release.  rst_sync[2] (the synchronised last stage) is the shared reset for
    // the tone source and the I2S transmitter; the raw lock is used ONLY as the
    // asynchronous clear of this dedicated chain (and for the immediate amp_sd
    // mute below), so it never bypasses the synchroniser into normal state CLEARs.
    // ------------------------------------------------------------------
    logic [2:0] rst_sync;
    logic       rst_n;

    always_ff @(posedge clk_audio or negedge audio_locked)
        if (!audio_locked) rst_sync <= 3'b000;
        else               rst_sync <= {rst_sync[1:0], 1'b1};

    assign rst_n = rst_sync[2];

    // ------------------------------------------------------------------
    // Continuous square-wave tone source (pure audio domain).
    // ------------------------------------------------------------------
    logic [31:0] tone_pcm;
    logic        tone_ready;    // i2s_amp_tx.in_ready consume strobe
    logic        tone_started;  // sticky first-handshake flag

    tone_source u_tone (
        .clk    (clk_audio),
        .rst_n  (rst_n),
        .ready  (tone_ready),
        .pcm    (tone_pcm),
        .started(tone_started)
    );

    // ------------------------------------------------------------------
    // Read-only reuse of the existing I2S transmitter.  CLK_DIV=4 gives
    // BCLK = clk_audio/4; in_valid is tied high and diag_clear tied low because
    // this diagnostic never underflows and has no separate clear control.
    // ------------------------------------------------------------------
    i2s_amp_tx #(
        .CLK_DIV(4)
    ) u_i2s (
        .clk             (clk_audio),
        .rst_n           (rst_n),
        .diag_clear      (1'b0),
        .in_valid        (1'b1),
        .in_ready        (tone_ready),
        .in_data         (tone_pcm),
        .amp_bclk        (amp_bclk),
        .amp_ws          (amp_lrc),
        .amp_din         (amp_din),
        .underflow_pulse (),
        .underflow_sticky(),
        .frame_tick      ()
    );

    // Amplifier shutdown / channel select: high only while locked, reset
    // released, and at least one tone frame has been accepted.  Lock loss drops
    // this combinationally in the same cycle (raw audio_locked is kept here
    // deliberately for the immediate mute, while rst_n's release is synchronised).
    assign amp_sd = audio_locked & rst_n & tone_started;

endmodule

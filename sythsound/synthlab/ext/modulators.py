"""
Modulation machinery: envelopes, and the shapers you put a control signal through.

These are ordinary Blocks whose output you route into any parameter with
`Modulated`, or read yourself. Nothing here is special-cased, which means you can
use an oscillator as a modulator at audio rate, or an envelope as an audio source.
Oscillators and one-shot scans are in `generators`; this module holds the part
that depends on events rather than on a clock.

`ADSR` is the reason this module exists. Its length is not a parameter: the sustain
lasts as long as the gate is held and the release starts when the gate falls, so it
cannot be expressed as a fixed-length scan. `EnvelopeFollower` is the same idea
backwards -- it derives a control signal from audio.

Curves
------
Envelopes are generated by a phase ramp mapped through a curve function, rather
than by exponential decay to a threshold. That is deliberate: it makes the shape
exact and repeatable, keeps the segment length independent of the start level, and
lets you substitute any curve you like:

    curve_expo(x, k) with k=0 is linear, k>0 bends the tail, k<0 bends the attack.
"""

from __future__ import annotations

import math
from typing import Callable

import numpy as np

from ..core import Block, Param, Source, TAU


__all__ = [
    "ADSR",
    "Constant",
    "EnvelopeFollower",
    "SampleHold",
    "Smoothed",
    "curve_expo",
    "curve_pow",
]


def curve_expo(x: float, k: float) -> float:
    """Map x in [0,1] onto a curved [0,1] shape.

    `k = 0` is linear. Positive k gives the fast-rise/slow-fall shape of an analog
    envelope; negative k gives slow-rise/fast-fall. Implemented as
    `(1 - exp(-k*x)) / (1 - exp(-k))` so the endpoints stay exactly 0 and 1.
    """
    if abs(k) < 1e-9:
        return x
    return (1.0 - math.exp(-k * x)) / (1.0 - math.exp(-k))


def curve_pow(x: float, k: float) -> float:
    """`x ** exp(k)` -- the standard exponential shape, exact at both ends."""
    if abs(k) < 1e-9:
        return x
    return x ** math.exp(k)


class ADSR(Source):
    """Four-stage envelope with per-stage curves and an optional retrigger law.

    This is a `Source`: it GENERATES its contour and ignores whatever signal it is
    handed. Chaining it after an oscillator therefore discards the oscillator and
    outputs a plain DC ramp (which sounds like a click, because output hardware
    blocks DC). Apply it with `Amp` instead:

        Chain(osc, env, Amp(env))

    Stages run on an internal phase counter, so segment lengths are exact:
    attack reaches exactly 1.0 at `attack` seconds regardless of curve, and the
    release always reaches exactly 0.0 so notes do not leave a DC offset or stop
    early.

    Trigger it by setting `gate = 1.0` (rising edge starts the attack) and release
    by setting `gate = 0.0`. You can also call `trigger()` / `release()` directly,
    or drive `gate` from another block. While released and finished, output is
    exactly 0.

    `curve` bends attack+decay+release together; `attack_curve`, `decay_curve`,
    `release_curve` override per stage (0 = linear).
    """

    gate = Param(0.0, doc="1.0 = held, 0.0 = released; rising edge retriggers")
    attack = Param(0.01, "s")
    decay = Param(0.2, "s")
    sustain = Param(0.6, "", 0.0, 1.0, doc="level held while gate is high")
    release = Param(0.3, "s")
    curve = Param(0.0, doc="global bend applied to every stage")
    attack_curve = Param(0.0, doc="overrides `curve` for the attack when non-zero")
    decay_curve = Param(0.0)
    release_curve = Param(0.0)
    velocity = Param(1.0, "", 0.0, 1.0)

    # Stage identifiers, readable from `.stage` after each sample.
    IDLE, ATTACK, DECAY, SUSTAIN, RELEASE = 0, 1, 2, 3, 4

    def reset(self, ctx) -> None:
        super().reset(ctx)
        self.stage = self.IDLE
        self.phase = 0.0
        self.level = 0.0
        self._last_gate = 0.0

    def trigger(self, velocity: float | None = None) -> None:
        """Start the attack from wherever the envelope currently is."""
        if velocity is not None:
            self.params["velocity"] = velocity
        self.stage = self.ATTACK
        self.phase = 0.0

    def note_off(self) -> None:
        """Enter the release stage.

        Named `note_off` rather than `release` on purpose: a method called
        `release` would shadow the `release` *parameter* of the same name.
        """
        if self.stage != self.IDLE:
            self.stage = self.RELEASE
            self.phase = 0.0
            # Start the release from the current level so short notes do not jump.
            self._release_from = self.level

    def _stage_curve(self, override_key: str) -> float:
        override = self.params[override_key]
        return override if abs(override) > 1e-9 else self.curve

    def process(self, ctx) -> float:
        dt = 1.0 / ctx.sr
        gate = self.gate
        # Edge detection: this is what makes `gate` behave like a key press.
        if gate > 0.5 and self._last_gate <= 0.5:
            self.trigger()
        elif gate <= 0.5 and self._last_gate > 0.5:
            self.note_off()
        self._last_gate = gate

        if self.stage == self.ATTACK:
            self.phase += dt / max(self.attack, 1e-6)
            if self.phase >= 1.0:
                self.phase = 0.0
                self.stage = self.DECAY
                self.level = 1.0
            else:
                self.level = curve_expo(self.phase, self._stage_curve("attack_curve"))
        elif self.stage == self.DECAY:
            self.phase += dt / max(self.decay, 1e-6)
            if self.phase >= 1.0:
                self.phase = 0.0
                self.stage = self.SUSTAIN
                self.level = self.sustain
            else:
                shaped = curve_expo(self.phase, self._stage_curve("decay_curve"))
                self.level = 1.0 + (self.sustain - 1.0) * shaped
        elif self.stage == self.SUSTAIN:
            self.level = self.sustain
        elif self.stage == self.RELEASE:
            self.phase += dt / max(self.release, 1e-6)
            if self.phase >= 1.0:
                self.phase = 0.0
                self.stage = self.IDLE
                self.level = 0.0
            else:
                shaped = curve_expo(self.phase, self._stage_curve("release_curve"))
                self.level = self._release_from * (1.0 - shaped)
        else:
            self.level = 0.0

        return self.level * self.velocity


class SampleHold(Block):
    """Samples its input every `period` seconds and holds the value.

    A building block for stepped modulation, bit-crushed control signals and
    arpeggio-like patterns. Set `period` to 0 to sample every sample (a no-op) and
    use `probability` to only accept a new value some of the time.
    """

    period = Param(0.1, "s")
    probability = Param(1.0, "", 0.0, 1.0)
    gate = Param(1.0, doc="0.0 freezes the current value")

    def reset(self, ctx) -> None:
        super().reset(ctx)
        self.last_output = 0.0
        self.acc = 0.0

    def process(self, x: float, ctx) -> float:
        if self.gate > 0.5:
            self.acc += 1.0 / ctx.sr
            if self.acc >= self.period:
                self.acc -= self.period
                if float(ctx.rng.uniform()) <= self.probability:
                    self.last_output = x
        return self.last_output


class Smoothed(Block):
    """Passes a parameter through a one-pole smoother.

    Indispensable for avoiding the clicks that stepped parameter changes cause:
    feed a new target in, get a continuous signal out. `time` is the approximate
    time constant in seconds (time to reach ~63% of the change).
    """

    time = Param(0.01, "s", doc="time constant; the 63% point")
    linear = Param(0.0, doc="1.0 = constant-rate slew instead of exponential")

    def reset(self, ctx) -> None:
        super().reset(ctx)
        self.last_output = 0.0
        self._primed = False

    def process(self, x: float, ctx=None) -> float:
        if not self._primed:
            self.last_output = x
            self._primed = True
            return self.last_output
        if self.linear > 0.5:
            # Constant slope: cross the full 0..1 range in `time` seconds.
            step = ctx.dt / max(self.time, 1e-6)
            delta = x - self.last_output
            if abs(delta) <= step:
                self.last_output = x
            else:
                self.last_output += step if delta > 0 else -step
        else:
            a = 1.0 - math.exp(-ctx.dt / max(self.time, 1e-6))
            self.last_output += a * (x - self.last_output)
        return self.last_output


class Constant(Source):
    """A fixed value as a Block -- useful as a modulation base, or as a probe.

    Because `Modulated` writes `base + depth * modulator`, putting a Constant in
    as the modulator gives you a programmable offset that shows up in `describe()`.

    The parameter is named `level`, not `value`: `Block` already records each
    block's output in `last_output`, and a data descriptor named `value` on a
    subclass would shadow it. `Block.__init__` rejects that collision.
    """

    level = Param(0.0)

    def process(self, ctx) -> float:
        return self.level


class EnvelopeFollower(Block):
    """Tracks the amplitude of its input -- an envelope follower.

    `attack` and `release` are separate time constants, which is what makes this
    usable as a compressor sidechain or an auto-wah control. For a proper
    sidechain you want two envelopes with different times; instantiate two.

    `mode`: 0 = peak (fast, ripple-prone), 1 = RMS (a one-pole on x^2, smoother).
    """

    attack = Param(0.01, "s")
    release = Param(0.1, "s")
    mode = Param(0.0)
    gain = Param(1.0)

    def reset(self, ctx) -> None:
        super().reset(ctx)
        self.env = 0.0
        self.square = 0.0

    def process(self, x: float, ctx=None) -> float:
        if self.mode < 0.5:
            level = abs(x)
        else:
            a_rms = 1.0 - math.exp(-ctx.dt / max(self.release, 1e-6))
            self.square += a_rms * (x * x - self.square)
            level = math.sqrt(max(self.square, 0.0))

        time = self.attack if level > self.env else self.release
        a = 1.0 - math.exp(-ctx.dt / max(time, 1e-6))
        self.env += a * (level - self.env)
        return self.env * self.gain
